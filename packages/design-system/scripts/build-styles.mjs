/**
 * Copies the stylesheet sources into `dist/styles` and writes the generated
 * token file alongside them.
 *
 * Keeping the CSS as separate source files rather than inlining it through a
 * bundler means the design system ships a stylesheet an application can import
 * directly, with no build-tool requirement of its own.
 *
 * The consumer and professional token blocks are generated from the TypeScript
 * token maps so the two palettes cannot drift. Generation reads the compiled
 * ESM artifact, which is why `build:styles` runs after `build:esm`.
 */

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDirectory = join(packageRoot, 'src', 'styles');
const outputDirectory = join(packageRoot, 'dist', 'styles');

mkdirSync(outputDirectory, { recursive: true });

const copied = [];

for (const entry of readdirSync(sourceDirectory, { withFileTypes: true })) {
  if (!entry.isFile() || !entry.name.endsWith('.css')) {
    continue;
  }
  const contents = readFileSync(join(sourceDirectory, entry.name), 'utf8');
  writeFileSync(join(outputDirectory, entry.name), contents, 'utf8');
  copied.push(entry.name);
}

const generatedModule = join(packageRoot, 'dist', 'esm', 'tokens', 'css-variables.js');
const { formatDesignTokens } = await import(pathToFileURL(generatedModule).href);

const consumerLines = formatDesignTokens('consumer')
  .split('\n')
  .filter((line) => line.trim().length > 0);

const professionalLines = formatDesignTokens('professional')
  .split('\n')
  .filter((line) => line.startsWith('  '));

const generated = [
  '/* Generated by scripts/build-styles.mjs from src/tokens. Do not edit by hand. */',
  consumerLines.join('\n'),
  "[data-dz-theme='professional'] {",
  professionalLines.join('\n'),
  '}',
  '',
].join('\n');

writeFileSync(join(outputDirectory, 'tokens.css'), generated, 'utf8');

process.stdout.write(`design-system styles: ${copied.join(', ')}, tokens.css (generated)\n`);
